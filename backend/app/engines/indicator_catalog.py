def macro_entry(
    key: str,
    label: str,
    region: str,
    *,
    unit: str = "percent",
    frequency: str = "mensal",
    source: str = "Provedor macroeconômico ainda não integrado",
    description: str | None = None,
) -> MacroIndicatorDefinition:
    return MacroIndicatorDefinition(
        key=key,
        label=label,
        description=description or label,
        region=region,
        unit=unit,
        frequency=frequency,
        source=source,
    )


